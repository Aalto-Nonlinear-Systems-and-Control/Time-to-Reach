"""Generate dReach (.drh) models from benchmark configs.

The model has one mode without jumps (run dReach with -k 0). Variable bounds and
the mode invariant are the benchmark domain, a clock tau measures the elapsed
time, the flow is f (or -f for backward benchmarks), init is the union of
initial sets at tau = 0 and goal is the union of target sets with tau inside
the time horizon. Equations and level-set functions are copied from the config
(dReach reads '^' as power and knows sin, cos, tan, atan, atan2, tanh, sqrt,
abs, log, exp).

    python -m tools.dreach.gen_drh DUFF_FIN_REA_BOX [-o model.drh]
"""

import argparse
import sys

import numpy as np

from tools.common import load_benchmark


def num(v):
    """A number in dReach syntax (no exponent, minus sign handled by the caller's context)."""
    return np.format_float_positional(float(v), trim="-")


def expr(text):
    return text.replace("**", "^")


def _bound_atoms(bounds):
    atoms = []
    for i, (lo, hi) in enumerate(bounds, start=1):
        if lo == hi:
            atoms.append(f"(x{i} = {num(lo)})")
        else:
            atoms += [f"(x{i} >= {num(lo)})", f"(x{i} <= {num(hi)})"]
    return atoms


def _and(atoms):
    return atoms[0] if len(atoms) == 1 else "(and " + " ".join(atoms) + ")"


def set_formula(spec):
    kind = spec["type"]
    if kind == "box":
        return _and(_bound_atoms(spec["bounds"]))
    if kind == "ball":
        terms = " + ".join(f"(x{i} - ({num(c)}))^2" for i, c in enumerate(spec["center"], start=1))
        r2 = float(f"{spec['radius'] ** 2:.15g}")  # 0.1**2 prints as 0.010000000000000002
        return f"({terms} <= {num(r2)})"
    if kind == "level_set":
        return _and([f"({expr(spec['function'])} <= 0)"] + _bound_atoms(spec["bounding_box"]))
    raise ValueError(f"unknown set type {kind!r}")


def union_formula(specs):
    parts = [set_formula(s) for s in specs]
    return parts[0] if len(parts) == 1 else "(or " + " ".join(parts) + ")"


def generate(benchmark_id):
    return generate_model(load_benchmark(benchmark_id))


def generate_model(bm):
    """The .drh model of a loaded benchmark."""
    cfg = bm.raw
    if bm.system.kind != "nonlinear":
        raise NotImplementedError("linear systems: write A x as equations first")
    t0, t1 = bm.time_horizon
    sign = "" if bm.direction == "forward" else "-"
    lines = [
        f"// Generated by tools/dreach/gen_drh.py from configs/benchmarks/{bm.id}.json; do not edit.",
        f"// {bm.description}",
        f"// direction: {bm.direction}; expected: {bm.expected_result}",
        "",
    ]
    for i, (lo, hi) in enumerate(bm.domain.bounds, start=1):
        lines.append(f"[{num(lo)}, {num(hi)}] x{i};")
    lines += [f"[0, {num(t1)}] tau;", f"[0, {num(t1)}] time;", "", "{mode 1;", ""]
    invariants = [f"{a};" for a in _bound_atoms(bm.domain.bounds)] + [f"(tau <= {num(t1)});"]
    lines.append("invt:")
    lines += [f"\t{a}" for a in invariants]
    lines.append("")
    lines.append("flow:")
    for i, eq in enumerate(bm.system.equations, start=1):  # parameters and definitions substituted
        lines.append(f"\td/dt[x{i}] = {sign}({expr(eq)});")
    lines += ["\td/dt[tau] = 1;", "", "jump:", "", "}", ""]
    lines += ["init:", f"@1 (and {union_formula(cfg['initial_sets'])} (tau = 0));", ""]
    lines += ["goal:", f"@1 (and {union_formula(cfg['target_sets'])} (tau >= {num(t0)}) (tau <= {num(t1)}));", ""]
    return "\n".join(lines)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("benchmark")
    parser.add_argument("-o", "--output")
    args = parser.parse_args(argv)
    text = generate(args.benchmark)
    if args.output:
        with open(args.output, "w") as f:
            f.write(text)
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
